/**
 * The nominal distance maintained between devices by the attraction-repulsion behavior.
 */
const val NOMINAL_DISTANCE = 20.0

/**
 * Computes the displacement generated by attraction-repulsion interactions with neighboring devices.
 *
 * Each neighbor exerts an attractive force proportional to its distance and an inverse-square repulsive force.
 * The repulsion coefficient is derived from [attractionCoefficient] and [desiredDistance], so that the two forces
 * balance when the distance between two devices is equal to [desiredDistance].
 *
 * @param currentPosition The current position of the device.
 * @param attractionCoefficient The coefficient controlling the magnitude of the attraction-repulsion forces.
 * @param desiredDistance The distance at which attraction and repulsion between two devices are balanced.
 * @return The displacement resulting from the attraction-repulsion interactions with neighboring devices.
 */
fun <ID : Comparable<ID>> Aggregate<ID>.attractionRepulsion(
    currentPosition: Position,
    attractionCoefficient: Double,
    desiredDistance: Double,
): SpeedControl2D = sharing(currentPosition) { positions ->
    val displacements = positions.map { (id, position) ->
        when (id) {
            localId -> zeroSpeed
            else -> attractionRepulsionForce(position - currentPosition, attractionCoefficient, desiredDistance)
        }
    }
    val displacement: SpeedControl2D = displacements.all.fold(zeroSpeed) { acc, force -> acc + force.value }
    val newPosition: Position = Position(currentPosition.x + displacement.x, currentPosition.y + displacement.y)
    newPosition.yielding { displacement } 
}

/**
 * The attraction-repulsion force exerted by a neighbor located at [relativePosition] (i.e., `neighbor - self`).
 * See [attractionRepulsion] for the meaning of [attractionCoefficient] and [desiredDistance].
 */
fun attractionRepulsionForce(
    relativePosition: Vector2D,
    attractionCoefficient: Double,
    desiredDistance: Double,
): SpeedControl2D {
    val distance = relativePosition.norm
    if (distance == 0.0) return zeroSpeed
    val direction: SpeedControl2D = relativePosition * (1.0 / distance)
    val attractionForce: Double = attractionCoefficient * distance
    val repulsionCoefficient: Double = attractionCoefficient * desiredDistance.pow(3)
    val repulsionForce: Double = repulsionCoefficient / distance.pow(2)
    val netForce: Double = attractionForce - repulsionForce
    return direction * netForce
}

/**
 * Computes the displacement generated by repulsion-only interactions with neighboring devices.
 *
 * Each neighbor exerts only the inverse-square repulsive force of [attractionRepulsion] (no attractive component).
 * As in [attractionRepulsion], the repulsion coefficient is derived from [coefficient] and [desiredDistance]
 * (`coefficient * desiredDistance^3`), so the repulsion has the same magnitude it would have there.
 *
 * @param currentPosition The current position of the device.
 * @param coefficient The coefficient controlling the magnitude of the repulsive force.
 * @param desiredDistance The reference distance used to scale the repulsion.
 * @return The displacement resulting from the repulsive interactions with neighboring devices.
 */
fun <ID : Comparable<ID>> Aggregate<ID>.repulsion(
    currentPosition: Position,
    coefficient: Double,
    desiredDistance: Double,
): SpeedControl2D = sharing(currentPosition) { positions ->
    val displacements = positions.map { (id, position) ->
        when (id) {
            localId -> zeroSpeed
            else -> repulsionForce(position - currentPosition, coefficient, desiredDistance)
        }
    }
    val displacement: SpeedControl2D = displacements.all.fold(zeroSpeed) { acc, force -> acc + force.value }
    val newPosition: Position = Position(currentPosition.x + displacement.x, currentPosition.y + displacement.y)
    newPosition.yielding { displacement }
}

/**
 * The repulsive force exerted by a neighbor located at [relativePosition] (i.e., `neighbor - self`).
 * It points away from the neighbor. See [repulsion] for the meaning of [coefficient] and [desiredDistance].
 */
fun repulsionForce(relativePosition: Vector2D, coefficient: Double, desiredDistance: Double): SpeedControl2D {
    val distance = relativePosition.norm
    if (distance == 0.0) return zeroSpeed
    val direction: SpeedControl2D = relativePosition * (1.0 / distance)
    val repulsionCoefficient: Double = coefficient * desiredDistance.pow(3)
    val repulsionForce: Double = repulsionCoefficient / distance.pow(2)
    return direction * (-repulsionForce)
}

/**
 * An entry point for the attraction-repulsion behavior in a Collektive simulation.
 *
 * This function computes the displacement for the device based on attraction-repulsion interactions with neighboring
 * devices and applies the resulting velocity to the device.
 *
 * @param device The Collektive device representing the current node in the simulation.
 * @param locationSensor The sensor providing the current coordinates of the device.
 */
fun Aggregate<Int>.attractionRepulsionEntrypoint(
    device: CollektiveDevice<Euclidean2DPosition>,
    locationSensor: LocationSensor,
) = with(device) {
    val displace =
        attractionRepulsion(
            locationSensor.coordinates(),
            attractionCoefficient = 0.001,
            desiredDistance = NOMINAL_DISTANCE,
        )
    applyVelocity(displace)
}
